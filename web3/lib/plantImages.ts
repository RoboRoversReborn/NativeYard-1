export function getPlantImage(
  sci?: string | null,
  common?: string | null,
  explicitUrl?: string | null
): string | null {
  if (explicitUrl) return explicitUrl;
  if (!sci) return null;
  if (PLANT_IMAGES[sci]) return PLANT_IMAGES[sci];
  // Try genus match
  if (sci.includes(" ")) {
    const genus = sci.split(" ")[0];
    for (const [key, path] of Object.entries(PLANT_IMAGES)) {
      if (key.startsWith(genus + " ")) return path;
    }
  }
  return null;
}

